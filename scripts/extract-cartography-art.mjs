// Pulls the Directions puzzle's map icons out of Kenney's Cartography Pack
// (CC0, https://kenney.nl/assets/cartography-pack) into a TypeScript module.
//
//   node scripts/extract-cartography-art.mjs path/to/cartographyPack_vector.svg
//
// The pack's vector sheet lays its icons out on a 64-unit grid, each drawn as
// a thick outline path and a thin detail path. Icons are picked by grid cell
// and moved to the origin, so each one sits in a 64×64 box.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/components/puzzles/Directions/art.ts';
const CELL = 64;

/** Icon name -> [column, row] on the sheet. */
const ICONS = {
  hut: [3, 1],
  tent: [6, 1],
  ship: [0, 2],
  pine: [9, 2],
  pineTall: [10, 2],
  pines: [11, 2],
  rocks: [0, 3],
  mountains: [1, 3],
  peaks: [2, 3],
  cave: [3, 3],
  rocksTall: [6, 3],
  rocksLow: [7, 3],
  palm: [11, 3],
  palmLarge: [12, 3],
  skullRock: [0, 4],
  lighthouse: [2, 4],
  stones: [4, 4],
  campfire: [5, 4],
  well: [6, 4],
  chest: [7, 4],
  waves: [5, 5],
  compass: [8, 6],
};

const svg = readFileSync(process.argv[2], 'utf8');
const paths = [...svg.matchAll(/stroke-width="([\d.]+)"[^>]*?d="([^"]+)"/g)].map(([, width, d]) => {
  const n = [...d.matchAll(/-?[\d.]+/g)].map(m => Number(m[0]));
  const xs = n.filter((_, i) => i % 2 === 0);
  const ys = n.filter((_, i) => i % 2 === 1);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2;
  const cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  return { thick: width === '2', d, col: Math.floor(cx / CELL), row: Math.floor(cy / CELL) };
});

// Every command is M, L or Q with absolute coordinates, so numbers come in x,y pairs
function shift(d, dx, dy) {
  let i = 0;
  return d.replace(/-?[\d.]+/g, m => {
    const v = Number(m) - (i++ % 2 === 0 ? dx : dy);
    return String(Math.round(v * 100) / 100);
  });
}

const entries = Object.entries(ICONS).map(([name, [col, row]]) => {
  const mine = paths.filter(p => p.col === col && p.row === row);
  if (mine.length === 0) throw new Error(`No paths for ${name} at ${col},${row}`);
  const join = thick => mine.filter(p => p.thick === thick).map(p => shift(p.d, col * CELL, row * CELL)).join(' ');
  const n = mine.flatMap(p => [...shift(p.d, col * CELL, row * CELL).matchAll(/-?[\d.]+/g)].map(m => Number(m[0])));
  const xs = n.filter((_, i) => i % 2 === 0);
  const ys = n.filter((_, i) => i % 2 === 1);
  const box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)].map(Math.round);
  return `  ${name}: {\n    box: [${box.join(', ')}],\n    thick: '${join(true)}',\n    thin: '${join(false)}',\n  },`;
});

writeFileSync(
  OUT,
  `// Generated by scripts/extract-cartography-art.mjs from Kenney's Cartography
// Pack (CC0, https://kenney.nl/assets/cartography-pack). Don't hand-edit.
//
// Each icon is line art in a 64×64 box: a thick outline and thin details, both
// meant to be stroked, never filled. Most stand on a baseline near y = 60.

export interface Icon {
  /** The drawing's extent, [minX, minY, maxX, maxY]. */
  box: [number, number, number, number];
  thick: string;
  thin: string;
}

export const ART = {
${entries.join('\n')}
} satisfies Record<string, Icon>;

export type ArtName = keyof typeof ART;
`
);
console.log(`Wrote ${Object.keys(ICONS).length} icons to ${OUT}`);
